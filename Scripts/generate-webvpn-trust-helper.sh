#!/bin/bash

# 生成 CSUSTPlanet/Helpers/WebVPNTrustHelper.swift
#
# 学校于 2026-10-10 更换 *.csust.edu.cn 证书后，只有 vpn.csust.edu.cn 的服务器没有下发中间证书
# （authserver、ehall 等站点下发的都是完整证书链），而该证书链需要经过 Certum 的交叉签名证书
# 才能校验到系统信任的根证书，客户端无法完成 TLS 校验（-1202），WebVPN 模式完全不可用。
#
# 本脚本从证书链完整的校内站点抓取中间证书内嵌到 Swift 文件中，App 在系统默认校验失败时用它
# 补全证书链后重新校验；学校修好服务端后该逻辑自动不再触发。学校换证书后重新运行本脚本即可。

set -euo pipefail

cd "$(dirname "$0")/.."

SOURCE_HOST="authserver.csust.edu.cn"
OUTPUT_FILE="CSUSTPlanet/Helpers/WebVPNTrustHelper.swift"

TEMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TEMP_DIR"' EXIT

echo "从 $SOURCE_HOST 获取证书链..."

openssl s_client \
  -connect "$SOURCE_HOST:443" \
  -servername "$SOURCE_HOST" \
  -showcerts </dev/null >"$TEMP_DIR/chain.txt" 2>/dev/null

awk -v dir="$TEMP_DIR" '
  /-----BEGIN CERTIFICATE-----/ { count++; in_cert = 1 }
  in_cert { print > (dir "/cert" count ".pem") }
  /-----END CERTIFICATE-----/ { in_cert = 0 }
' "$TEMP_DIR/chain.txt"

CERT_COUNT="$(find "$TEMP_DIR" -name 'cert*.pem' | wc -l | tr -d ' ')"

if [ "$CERT_COUNT" -lt 2 ]; then
  echo "错误：$SOURCE_HOST 只下发了 $CERT_COUNT 张证书，取不到中间证书。" >&2
  exit 1
fi

CERT_LITERALS=""

for ((index = 2; index <= CERT_COUNT; index++)); do
  PEM_FILE="$TEMP_DIR/cert$index.pem"
  openssl x509 -in "$PEM_FILE" -outform DER -out "$PEM_FILE.der"
  echo "  [$index] $(openssl x509 -in "$PEM_FILE" -noout -subject | sed -n 's/.*CN *= *//p')"
  BASE64="$(openssl base64 -A -in "$PEM_FILE.der")"
  CERT_LITERALS="$CERT_LITERALS        \"$BASE64\",
"
done

echo "内置 $((CERT_COUNT - 1)) 张中间证书，写入 $OUTPUT_FILE"

cat >"$OUTPUT_FILE" <<EOF
//
//  WebVPNTrustHelper.swift
//  CSUSTPlanet
//
//  Auto-generated by Scripts/generate-webvpn-trust-helper.sh. Do not edit.
//

import Alamofire
import Foundation
import Security

enum WebVPNTrustHelper {
    static let host = "vpn.csust.edu.cn"

    private static let intermediateCertificateBase64: [String] = [
$CERT_LITERALS    ]

    private static let intermediateCertificates: [SecCertificate] =
        intermediateCertificateBase64
        .compactMap { Data(base64Encoded: \$0) }
        .compactMap { SecCertificateCreateWithData(nil, \$0 as CFData) }

    static func isTrusted(_ trust: SecTrust, forHost host: String) -> Bool {
        guard host.caseInsensitiveCompare(Self.host) == .orderedSame else { return false }

        if SecTrustEvaluateWithError(trust, nil) { return true }

        guard let leafCertificate = (SecTrustCopyCertificateChain(trust) as? [SecCertificate])?.first else {
            return false
        }

        var augmentedTrust: SecTrust?
        let status = SecTrustCreateWithCertificates(
            ([leafCertificate] + intermediateCertificates) as CFArray,
            SecPolicyCreateSSL(true, host as CFString),
            &augmentedTrust
        )

        guard status == errSecSuccess, let augmentedTrust else { return false }

        return SecTrustEvaluateWithError(augmentedTrust, nil)
    }
}

struct WebVPNServerTrustEvaluator: ServerTrustEvaluating {
    func evaluate(_ trust: SecTrust, forHost host: String) throws {
        guard WebVPNTrustHelper.isTrusted(trust, forHost: host) else {
            throw URLError(.serverCertificateUntrusted)
        }
    }
}
EOF
